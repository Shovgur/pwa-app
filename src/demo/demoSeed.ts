function buildBookings(): DemoBooking[] {
  const bookings: DemoBooking[] = []
  let id = 1001
  const clients = [
    { id: 1001, name: 'Демо Клиент', phone: '+79001234567' },
    { id: 1002, name: 'Анна Иванова', phone: '+79007654321' },
    { id: 1003, name: 'Пётр Сидоров', phone: '+79005551234' },
  ]

  for (let i = 0; i < 30; i++) {
    const venue = VENUES[i % VENUES.length]
    const client = clients[i % clients.length]
    const status = STATUSES[i % STATUSES.length]
    const durationMinutes = i % 3 === 0 ? 90 : 60
    const timeFrom = TIMES[i % TIMES.length]
    const timeTo = addMinutes(timeFrom, durationMinutes)
    const amount = Math.round((venue.pricePerHour * durationMinutes) / 60)
    const paidAmount =
      status === 'paid' || status === 'completed' ? amount : 0
    const dayOffset = (i % 14) - 5

    bookings.push({
      id,
      code: `BG-${1000 + id}`,
      companyId: venue.companyId,
      clientId: client.id,
      customerName: client.name,
      customerPhone: client.phone,
      venueId: venue.id,
      venueName: venue.name,
      venueKind: venue.venueKind,
      venueSport: venue.sportType ?? null,
      venueAddress: venue.address,
      venueEmoji: null,
      venueColor: null,
      venueRef: `partner:${venue.id}`,
      date: isoDaysFromToday(dayOffset),
      time: timeFrom,
      timeFrom,
      timeTo,
      durationMinutes,
      guests: 1 + (i % 4),
      amount,
      paidAmount,
      paymentMethod: i % 2 === 0 ? 'online' : 'cash',
      status,
      comment: i % 5 === 0 ? 'Позвонить за час' : null,
      createdAt: new Date(Date.now() - i * 86400000).toISOString(),
    })
    id += 1
  }
  return bookings
}

